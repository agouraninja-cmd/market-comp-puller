-- migrations/065-bov-desk.sql
-- 065 · The BOV desk: the brokers found for each Broker Opinion of Value
-- request, the email drafted to each, and what became of it (2026-11-20).
-- Rules: bov-desk.js. Notes: .claude/rules/bov-desk.md.
--
-- DEPLOY ORDER IS SOFT. Nothing but the BOV desk reads or writes these two
-- tables, and every write from the lead route is fire-and-forget, so a deploy
-- that runs ahead of this file costs only the desk: a request is still
-- stored, the owner and the requester are still mailed exactly as before, and
-- /admin/bov says "run migration 065" instead of listing brokers. Run it
-- before expecting the automation to do anything.
--
-- OWNER-ONLY. Read and written only by the ADMIN_KEY-gated /api/admin/bov
-- route, the lead route's own kickoff, and the two /bov/accept routes (which
-- are authenticated by an HMAC of the match id and touch one row). No member
-- surface, no corpus and no public page reads either table. DB-only: the
-- routes refuse without a database rather than fall back to a file Render
-- erases on deploy. They hold a requester's lead id and brokers' public
-- contact details; the requester's own name, email and phone stay in `leads`.
--
-- Purely additive and idempotent; test/bov-desk.test.js fails the build if a
-- destructive statement appears in this file.

-- One row per request that the desk has started on.
create table if not exists bov_requests (
  -- leads.id. No FK, for 015's reason: `leads` predates this folder and a
  -- deleted lead must not fail here; the desk simply stops listing it.
  lead_id bigint primary key,
  -- canonical marketOf() form, and the lead's property type: the pair a
  -- broker is found for, and the key brokers are reused under (the bench).
  market text not null,
  property_type text not null,
  -- The requester's own share link (/r/<id>), validated by the lead route.
  -- The `leads` table has no column for it, so before this it lived only in
  -- the notification email.
  report_url text,
  -- Restates bov-desk.js REQUEST_STATES; keep the two in step.
  state text not null default 'new'
    check (state in ('new', 'searching', 'ready', 'none_found', 'failed', 'introduced', 'closed')),
  -- Why a search found nobody or failed, in words the desk can show.
  note text,
  -- The broker this request went to. Claimed with `introduced_match_id=is.null`
  -- in the filter, which is what makes "the first broker to accept" one broker
  -- when two click at once.
  introduced_match_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists bov_requests_market_type_idx
  on bov_requests (market, property_type, created_at desc);
alter table bov_requests enable row level security;

-- One row per broker offered a request.
create table if not exists bov_matches (
  -- Generated by the server before the insert, because the accept link in
  -- the drafted email is built from it.
  id uuid primary key default gen_random_uuid(),
  lead_id bigint not null,
  name text not null,
  firm text,
  email text,
  phone text,
  -- The one clause the search may contribute to the email ("your office
  -- sales and leasing work across Greater Rhode Island").
  fit text,
  license text,
  -- The page the contact details were read from.
  source_url text,
  -- How far the address is trusted: none, match (same domain as source_url),
  -- free (a free-mail address), differs, or manual (the owner typed it).
  email_check text,
  -- Restates bov-desk.js ORIGINS: a web search, reused from an earlier
  -- request in the market, typed by the owner, or a member broker who asked
  -- for the lead from their pipeline.
  origin text not null default 'search'
    check (origin in ('search', 'bench', 'manual', 'platform')),
  -- Restates bov-desk.js MATCH_STATUSES; keep the two in step.
  status text not null default 'draft'
    check (status in ('draft', 'sent', 'accepted', 'introduced', 'declined', 'skipped')),
  -- The email exactly as it will be sent. Stored, so what the owner reads on
  -- the desk is what goes out, and an edit is a row update.
  subject text,
  body text,
  sent_at timestamptz,
  -- When the broker accepted or declined.
  answered_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists bov_matches_lead_id_idx on bov_matches (lead_id);
alter table bov_matches enable row level security;

